def gen_display_defs():
    import importlib
    m = importlib.import_module("widgets.display_keyboard_defs")
    names = ["ansi_100", "ansi_80", "ansi_70", "iso_100", "iso_80", "iso_70",
             "mods", "mods_narrow"]
    lines = [HEADER]
    for n in names:
        camel = n.split("_")[0] + "".join(p.title() for p in n.split("_")[1:])
        lines.append("const String displayDef%s = %s;\n\n" % (
            camel[0].upper() + camel[1:], ds(getattr(m, n).strip())))
    with open(os.path.join(OUT, "ui", "display_keyboard_defs.dart"), "w") as f:
        f.write("".join(lines))



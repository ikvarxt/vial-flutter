# any_keycode.py imports simpleeval, which is not needed for table generation.
import types
import ast as _ast
_se = types.ModuleType("simpleeval")
_se.DEFAULT_OPERATORS = {}
def _simple_eval(expr, names=None, functions=None, operators=None):
    env = dict(names or {})
    env.update(functions or {})
    return eval(compile(_ast.parse(expr, mode="eval"), "<any_keycode>", "eval"), {"__builtins__": {}}, env)
_se.simple_eval = _simple_eval
sys.modules.setdefault("simpleeval", _se)

HEADER = (
    "// SPDX-License-Identifier: GPL-2.0-or-later\n"
    "// GENERATED by tool/gen_tables.py from vial-gui sources. Do not edit.\n\n"
)


def ds(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def gen_kc(modname, dartname, prefix):
    import importlib
    m = getattr(importlib.import_module("keycodes." + modname), modname)
    lines = [HEADER, "const Map<String, int> %sKc = {\n" % prefix]
    for k, v in m.kc.items():
        lines.append("  %s: 0x%X,\n" % (ds(k), v))
    lines.append("};\n\n")
    lines.append("const Set<int> %sMasked = {\n" % prefix)
    for k in sorted(m.masked):
        lines.append("  0x%X,\n" % k)
    lines.append("};\n")
    with open(os.path.join(OUT, "keycodes", dartname), "w") as f:
        f.write("".join(lines))



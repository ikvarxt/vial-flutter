def dart_kc(k):
    args = [ds(k.qmk_id), ds(k.label)]
    if k.tooltip is not None:
        args.append("tooltip: %s" % ds(k.tooltip))
    if k.masked:
        args.append("masked: true")
    if k.printable is not None:
        args.append("printable: %s" % ds(k.printable))
    extra_alias = k.alias[1:]
    if extra_alias:
        args.append("alias: [%s]" % ", ".join(ds(a) for a in extra_alias))
    rec = [a for a, kc in Keycode.recorder_alias_to_keycode.items() if kc is k]
    if rec:
        args.append("recorderAlias: [%s]" % ", ".join(ds(a) for a in rec))
    if k.requires_feature is not None:
        args.append("requiresFeature: %s" % ds(k.requires_feature))
    return "Keycode(%s)" % ", ".join(args)


def gen_keycode_defs():
    global Keycode
    from keycodes import keycodes as m
    Keycode = m.Keycode
    lists = [
        ("KEYCODES_SPECIAL", "keycodesSpecial"),
        ("KEYCODES_BASIC", "keycodesBasic"),
        ("KEYCODES_BASIC_NUMPAD", "keycodesBasicNumpad"),
        ("KEYCODES_BASIC_NAV", "keycodesBasicNav"),
        ("KEYCODES_SHIFTED", "keycodesShifted"),
        ("KEYCODES_ISO", "keycodesIso"),
        ("KEYCODES_ISO_KR", "keycodesIsoKr"),
        ("KEYCODES_BOOT", "keycodesBoot"),
        ("KEYCODES_MODIFIERS", "keycodesModifiers"),
        ("KEYCODES_QUANTUM", "keycodesQuantum"),
        ("KEYCODES_BACKLIGHT", "keycodesBacklight"),
        ("KEYCODES_MEDIA", "keycodesMedia"),
        ("KEYCODES_MACRO_BASE", "keycodesMacroBase"),
        ("KEYCODES_MIDI_BASIC", "keycodesMidiBasic"),
        ("KEYCODES_MIDI_ADVANCED", "keycodesMidiAdvanced"),
    ]
    lines = [HEADER, "import 'keycode.dart';\n\n"]
    # BASIC already contains NUMPAD and NAV (extended in the Python source);
    # emit the sub-lists as views on the shared instances so registration
    # happens once.
    basic = m.KEYCODES_BASIC
    numpad_start = len(basic) - len(m.KEYCODES_BASIC_NUMPAD) - len(m.KEYCODES_BASIC_NAV)
    nav_start = len(basic) - len(m.KEYCODES_BASIC_NAV)
    iso_kr_start = len(m.KEYCODES_ISO) - len(m.KEYCODES_ISO_KR)
    for pyname, dartname in lists:
        if pyname == "KEYCODES_BASIC_NUMPAD":
            lines.append("final List<Keycode> %s = keycodesBasic.sublist(%d, %d);\n\n" % (dartname, numpad_start, nav_start))
            continue
        if pyname == "KEYCODES_BASIC_NAV":
            lines.append("final List<Keycode> %s = keycodesBasic.sublist(%d);\n\n" % (dartname, nav_start))
            continue
        if pyname == "KEYCODES_ISO_KR":
            lines.append("final List<Keycode> %s = keycodesIso.sublist(%d);\n\n" % (dartname, iso_kr_start))
            continue
        lines.append("final List<Keycode> %s = [\n" % dartname)
        for k in getattr(m, pyname):
            lines.append("  %s,\n" % dart_kc(k))
        lines.append("];\n\n")
    with open(os.path.join(OUT, "keycodes", "keycode_defs.dart"), "w") as f:
        f.write("".join(lines))


